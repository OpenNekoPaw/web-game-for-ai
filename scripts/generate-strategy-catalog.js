import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const strategiesDirectory = join(projectRoot, 'strategies', 'ddz');
const outputPath = join(projectRoot, 'server', 'strategy-catalog-runtime.js');

const files = (await readdir(strategiesDirectory)).filter((name) => name.endsWith('.md')).sort();
const strategies = await Promise.all(files.map(async (name) => {
  const markdown = await readFile(join(strategiesDirectory, name), 'utf8');
  const metadata = parseFrontmatter(markdown);
  if (!metadata.id || !metadata.name) throw new Error(`invalid_strategy:${name}`);
  return {
    id: metadata.id,
    name: metadata.name,
    description: metadata.description || '',
    updatedAt: 1,
    hash: createHash('sha256').update(markdown).digest('hex').slice(0, 12),
    markdown
  };
}));

if (!strategies.length) throw new Error('strategies_unavailable');
const defaultStrategyId = strategies.some(({ id }) => id === 'default') ? 'default' : strategies[0].id;
const source = `// Generated by scripts/generate-strategy-catalog.js.
// Read-only management/query data; the game engine never imports this module.
const strategies = ${JSON.stringify(strategies, null, 2)};
const defaultStrategyId = ${JSON.stringify(defaultStrategyId)};

export function listStrategies() {
  return {
    defaultStrategyId,
    strategies: strategies.map(({ markdown, ...metadata }) => ({ ...metadata }))
  };
}

export function getStrategy(strategyId) {
  const resolvedId = strategyId || defaultStrategyId;
  const strategy = strategies.find(({ id }) => id === resolvedId);
  if (!strategy) throw new Error('strategy_not_found');
  return structuredClone(strategy);
}
`;

await writeFile(outputPath, source);

function parseFrontmatter(markdown) {
  const match = markdown.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
  if (!match) throw new Error('invalid_strategy');
  return Object.fromEntries(match[1].split(/\r?\n/).filter(Boolean).map((line) => {
    const separator = line.indexOf(':');
    if (separator < 1) throw new Error('invalid_strategy');
    return [line.slice(0, separator).trim(), line.slice(separator + 1).trim()];
  }));
}
